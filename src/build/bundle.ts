// Binary entrypoint generator + hooks.json emitter
// See docs/SPEC.md § Build CLI

import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { dirname, isAbsolute, join, resolve } from "node:path";
import type { HookModule } from "../core/types.js";

/** Build modes for `hook-kit build`.
 *  - `shell` (default): produces an `hk` shell wrapper. Agent-agnostic.
 *  - `cc-tools`: produces a Claude Code tool-call adapter binary for
 *    Edit/Write/NotebookEdit/Read events that bypass the shell. Opt-in. */
export type AdapterName = "shell" | "cc-tools";

export const SUPPORTED_ADAPTERS: readonly AdapterName[] = ["shell", "cc-tools"];

interface AdapterWiring {
  readonly entrypointBody: (entrypoint: string) => string;
}

// User entrypoints are loaded via dynamic `import().then(async …)` rather
// than a static `import default from …` so the user's default export can be
// either:
//   1. A synchronous module array  (`export default [createModule(…)]`)
//   2. An async-or-sync function   (`export default async () => [createModule(…)]`)
//
// (2) lets the user perform async init (e.g. read a config file) without
// putting top-level await in their hooks.ts — `bun build --compile --bytecode`
// rejects TLA in any module reachable from the entrypoint, so the async work
// must live inside an exported function that the wrapper calls after import.
// (BUG-003 in docs/BUGS.md.)
function dynamicLoadAndDispatch(entrypoint: string, dispatch: string): string {
  return [
    `import(${JSON.stringify(entrypoint)}).then(`,
    "  async (mod) => {",
    "    const exported = mod.default;",
    '    const modules = typeof exported === "function" ? await exported() : exported;',
    `    ${dispatch}`,
    "  },",
    "  (err) => {",
    // biome-ignore lint/suspicious/noTemplateCurlyInString: ${…} is meaningful in the emitted wrapper source
    "    process.stderr.write(`[hook-kit] failed to load entrypoint: ${err instanceof Error ? err.message : String(err)}\\n`);",
    "    process.exit(1);",
    "  },",
    ");",
    "",
  ].join("\n");
}

const ADAPTER_WIRING: Readonly<Record<AdapterName, AdapterWiring>> = {
  shell: {
    entrypointBody: (entrypoint) =>
      [
        "// Generated by hook-kit build — do not edit",
        'import { runShell } from "@questi0nm4rk/hook-kit/wrapper/hk";',
        "",
        dynamicLoadAndDispatch(entrypoint, "runShell(modules);"),
      ].join("\n"),
  },
  "cc-tools": {
    entrypointBody: (entrypoint) =>
      [
        "// Generated by hook-kit build — do not edit",
        'import { run } from "@questi0nm4rk/hook-kit";',
        'import { claudeCodeAdapter } from "@questi0nm4rk/hook-kit/adapters/claude-code";',
        "",
        dynamicLoadAndDispatch(entrypoint, "run(modules, claudeCodeAdapter);"),
      ].join("\n"),
  },
};

export interface BundleOptions {
  /** Path (relative or absolute) to the user's hook entrypoint that
   *  default-exports a `HookModule[]`. Resolved relative to cwd. */
  readonly entrypoint: string;
  /** Where the compiled binary lands. Resolved relative to cwd. */
  readonly out: string;
  /** Which build mode. Defaults to `shell`. */
  readonly adapter: AdapterName;
  /** Optional `bun build --target=<value>` for cross-compilation
   *  (e.g. `bun-linux-arm64`, `bun-darwin-x64`). When omitted, bun
   *  builds for the host platform. Passed through verbatim — bun's own
   *  error surfaces if the value is unrecognized. */
  readonly target?: string;
}

/**
 * Generate the wrapper TS source the compiled binary starts from. The shape
 * differs per build mode: `shell` wires runShell() (no harness JSON),
 * `cc-tools` wires run() through the CC adapter for tool-call events.
 *
 * The user's entrypoint is loaded via dynamic `import()` so it may use
 * top-level await (BUG-003 in docs/BUGS.md).
 */
export function generateEntrypoint(opts: BundleOptions): string {
  return ADAPTER_WIRING[opts.adapter].entrypointBody(opts.entrypoint);
}

// ───────────────────────────── hooks.json ──────────────────────────────

export interface HooksJsonOptions {
  /** Absolute or `${CLAUDE_PLUGIN_ROOT}`-relative path to the binary. */
  readonly binaryPath: string;
  /** Per-hook timeout in seconds. */
  readonly timeout: number;
}

interface HookEntry {
  matcher: string;
  hooks: { type: "command"; command: string; timeout: number }[];
}

export interface HooksJson {
  hooks: Record<string, HookEntry[]>;
}

/**
 * Emit a CC hooks.json shape from the supplied modules. Each module produces
 * one entry per declared event. Disabled modules are skipped. Empty matchers
 * are preserved (the binary handles its own internal routing).
 */
export function generateHooksJson(
  modules: readonly HookModule[],
  opts: HooksJsonOptions,
): HooksJson {
  const hooks: Record<string, HookEntry[]> = {};
  for (const mod of modules) {
    if (mod.enabled === false) {
      continue;
    }
    const matcher = mod.matchers?.join("|") ?? "";
    for (const event of mod.events) {
      const list = hooks[event] ?? [];
      list.push({
        matcher,
        hooks: [
          {
            type: "command",
            command: opts.binaryPath,
            timeout: opts.timeout,
          },
        ],
      });
      hooks[event] = list;
    }
  }
  return { hooks };
}

// ─────────────────────────── runBuild() ────────────────────────────────

export interface BuildResult {
  /** Absolute path to the produced binary. */
  readonly binPath: string;
  /** stdout from the underlying bun build invocation. */
  readonly stdout: string;
  /** stderr from the underlying bun build invocation. */
  readonly stderr: string;
}

/**
 * Compile a hook-kit binary from a user entrypoint. Generates a thin wrapper
 * in a temp directory, runs `bun build --compile --bytecode`, and cleans up.
 * Throws on a non-zero exit from bun build (the caller decides how to surface).
 */
export async function runBuild(opts: BundleOptions): Promise<BuildResult> {
  const absEntry = isAbsolute(opts.entrypoint)
    ? opts.entrypoint
    : resolve(process.cwd(), opts.entrypoint);
  const absOut = isAbsolute(opts.out) ? opts.out : resolve(process.cwd(), opts.out);

  // Place the wrapper inside the user's plugin tree so bun's node_modules
  // resolution walks up into the plugin's package and finds hook-kit there.
  // A sibling tmpdir wouldn't see the user's deps.
  const pluginDir = dirname(absEntry);
  const work = mkdtempSync(join(pluginDir, ".hook-kit-build-"));
  const wrapperPath = join(work, "entry.ts");
  try {
    writeFileSync(
      wrapperPath,
      generateEntrypoint({ entrypoint: absEntry, out: absOut, adapter: opts.adapter }),
      "utf8",
    );

    const cmd = ["bun", "build", wrapperPath, "--compile", "--bytecode", "--outfile", absOut];
    if (opts.target !== undefined && opts.target !== "") {
      cmd.push(`--target=${opts.target}`);
    }
    const proc = Bun.spawn(cmd, {
      cwd: pluginDir,
      stdout: "pipe",
      stderr: "pipe",
    });
    const [stdout, stderr, exitCode] = await Promise.all([
      new Response(proc.stdout).text(),
      new Response(proc.stderr).text(),
      proc.exited,
    ]);

    if (exitCode !== 0) {
      throw new BuildError(`bun build exited with code ${exitCode}`, { stdout, stderr });
    }
    return { binPath: absOut, stdout, stderr };
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

export class BuildError extends Error {
  readonly stdout: string;
  readonly stderr: string;
  constructor(message: string, opts: { stdout: string; stderr: string }) {
    super(message);
    this.name = "BuildError";
    this.stdout = opts.stdout;
    this.stderr = opts.stderr;
  }
}
